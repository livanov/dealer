// `\b` in JS regexes only knows ASCII word characters, so it never fires next
// to Cyrillic letters. Rewrite it into a "no letter follows" lookahead.
/** @type {[string, RegExp][]} */
const COMPILED = RULES.map(([id, re]) => [
  id,
  new RegExp(re.source.replaceAll('\\b', '(?![а-яa-z0-9])'), 'u'),
]);

/** @returns {string} category id */
export function categorize({ brand = '', name = '', desc = '' }) {
  const text = `${brand} ${name} ${desc}`.toLowerCase();
  if (NONFOOD_BRANDS.some((b) => brand.toLowerCase().includes(b))) return 'nonfood';
  for (const [id, re] of COMPILED) if (re.test(text)) return id;
  return 'other';
}
